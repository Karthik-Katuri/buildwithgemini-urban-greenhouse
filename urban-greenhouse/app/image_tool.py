import re
import uuid
from typing import Any
from google import genai
from google.genai import types as genai_types
from google.genai.types import GenerateContentConfig, Modality
from google.cloud import storage
from google.adk.tools import ToolContext

BUCKET_NAME = "urban-greenhouse-qwiklabs-gcp-04-93b5deb0ee1a"
PROJECT_ID = "qwiklabs-gcp-04-93b5deb0ee1a"


async def generate_plant_image(plant_name_or_prompt: str, tool_context: ToolContext) -> dict[str, Any]:
    """Generates an image for a plant or indoor greenhouse setting, saves it as an artifact in the playground, and uploads it to public Cloud Storage.

    Args:
        plant_name_or_prompt: Name of the plant or visual description (e.g., 'Monstera Deliciosa in a sunlit living room', 'Fiddle Leaf Fig in a ceramic pot').
        tool_context: ADK ToolContext used to save session artifacts in Playground.

    Returns:
        A dictionary with the public image URL, artifact filename, and status.
    """
    try:
        # Step 1: Generate image using gemini-3.1-flash-lite-image in global region
        client = genai.Client(vertexai=True, project=PROJECT_ID, location="global")
        prompt = (
            f"A high-quality, beautiful photographic portrait of {plant_name_or_prompt}. "
            "Clean botanical presentation, natural lighting, healthy vibrant foliage."
        )

        response = client.models.generate_content(
            model="gemini-3.1-flash-lite-image",
            contents=prompt,
            config=GenerateContentConfig(
                response_modalities=[Modality.IMAGE]
            )
        )

        image_bytes: bytes | None = None
        mime_type = "image/jpeg"

        if response.candidates and response.candidates[0].content and response.candidates[0].content.parts:
            for part in response.candidates[0].content.parts:
                if part.inline_data and part.inline_data.data:
                    image_bytes = part.inline_data.data
                    if part.inline_data.mime_type:
                        mime_type = part.inline_data.mime_type
                    break

        if not image_bytes:
            return {"error": "No image data was generated by the model."}

        # Safe filename slug
        slug = re.sub(r"[^a-zA-Z0-9_-]", "_", plant_name_or_prompt.strip().lower())[:30]
        unique_suffix = uuid.uuid4().hex[:8]
        ext = "png" if "png" in mime_type else "jpg"
        filename = f"{slug}_{unique_suffix}.{ext}"

        # Step 2: (1) Save artifact for ADK Playground Artifacts panel
        artifact_part = genai_types.Part.from_bytes(data=image_bytes, mime_type=mime_type)
        try:
            await tool_context.save_artifact(filename=filename, artifact=artifact_part)
        except Exception as artifact_err:
            print(f"Note: artifact saving skipped ({artifact_err})")

        # Step 3: (2) Upload to public Cloud Storage without writing local files
        gcs_client = storage.Client(project=PROJECT_ID)
        bucket = gcs_client.bucket(BUCKET_NAME)
        blob = bucket.blob(f"plants/{filename}")
        blob.upload_from_string(image_bytes, content_type=mime_type)

        public_url = f"https://storage.googleapis.com/{BUCKET_NAME}/plants/{filename}"

        return {
            "status": "success",
            "plant": plant_name_or_prompt,
            "filename": filename,
            "public_url": public_url,
            "message": f"Image generated successfully. Available in artifacts and at {public_url}"
        }
    except Exception as e:
        return {"error": f"Failed to generate and upload image: {str(e)}"}
